// Pre-render math so the published article works without JavaScript or a CDN.
const fs = require('node:fs');
const path = require('node:path');
const katex = require('katex');

const root = path.resolve(__dirname, '..');
const contentDir = path.join(root, 'content');
const sources = fs.readdirSync(contentDir, { withFileTypes: true })
  .filter((entry) => entry.isFile() && entry.name.endsWith('.html'))
  .map((entry) => entry.name)
  .sort();
if (!sources.length) throw new Error('No article sources found in content/*.html');

const decode = (text) => text.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
// Render every source before writing, so a math error cannot leave a partial batch.
const articles = sources.map((filename) => {
  const source = path.join(contentDir, filename);
  const output = path.join(root, 'blog', path.basename(filename, '.html'), 'index.html');
  let equations = 0;
  let html;
  try {
    html = fs.readFileSync(source, 'utf8').replace(
      /<(span|div) data-math(?:="(block)")?>([\s\S]*?)<\/\1>/g,
      (_, tag, block, tex) => {
        equations += 1;
        const rendered = katex.renderToString(decode(tex.trim()), {
          displayMode: Boolean(block), output: 'htmlAndMathml',
          throwOnError: true, strict: 'error', trust: false,
        });
        return block
          ? `<div class="equation" tabindex="0" role="group" aria-label="公式，可横向滚动">${rendered}</div>`
          : rendered;
      },
    );
    if (html.includes('data-math')) throw new Error('Unrendered math in article source');
  } catch (error) {
    throw new Error(`Failed to render content/${filename}: ${error.message}`, { cause: error });
  }
  html = html.replace('<!doctype html>', `<!doctype html>\n<!-- Generated by npm run build:blog. Edit content/${filename}. -->`);
  return { output, html, equations };
});

for (const { output, html, equations } of articles) {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, html);
  console.log(`Rendered ${equations} formulas → ${path.relative(root, output)}`);
}

const packageDir = path.dirname(require.resolve('katex/package.json'));
const vendor = path.join(root, 'assets/vendor/katex');
fs.mkdirSync(vendor, { recursive: true });
fs.copyFileSync(path.join(packageDir, 'dist/katex.min.css'), path.join(vendor, 'katex.min.css'));
fs.cpSync(path.join(packageDir, 'dist/fonts'), path.join(vendor, 'fonts'), { recursive: true });
fs.copyFileSync(path.join(packageDir, 'LICENSE'), path.join(vendor, 'LICENSE'));
